// Usage: node scripts/generate-design-tokens.mjs ../harklight-app
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const appCommit = '094f54166baa1b3335051cc6c6d62302bbe63b72';
const appCheckout = process.argv[2];
if (!appCheckout) throw new Error('Pass the path to a Harklight App git checkout.');
const tokens = JSON.parse(execFileSync('git', ['-C', appCheckout, 'show', `${appCommit}:Design/tokens.json`], { encoding: 'utf8' }));

const colors = {
  bg: 'background', fg: 'text', muted: 'secondary', label: 'label', line: 'line',
  raised: 'raised', field: 'field', 'on-fg': 'onInverse', 'on-beam': 'onBeam',
  panel: 'panel', amber: 'amber', sky: 'sky', teal: 'teal', violet: 'violet', coral: 'coral',
  'accent-fill': 'accentFill', 'on-accent': 'onAccent',
};
const tints = { 'tint-request': 'request', 'tint-info': 'info', 'tint-done': 'done', 'tint-warn': 'warning', 'tint-error': 'error' };
const rowColors = {
  'row-request-ink': 'requestInk', 'row-request-fill': 'requestFill',
  'row-answered-ink': 'answeredInk', 'row-answered-fill': 'answeredFill',
};
const digest = {
  'digest-fill': 'background', 'digest-ink': 'foreground', 'digest-preview': 'preview',
  'digest-badge-border': 'badgeBorder', 'digest-disclosure-fill': 'disclosureBackground',
  'digest-disclosure-border': 'disclosureBorder',
};
const shapes = {
  'radius-card': 'card', 'radius-small': 'small', 'control-size': 'glassButton',
  'row-inset': 'rowHorizontalPadding', 'row-padding-block': 'rowVerticalPadding',
  'row-initials': 'rowInitials', 'message-initials': 'messageInitials',
  'selection-bar': 'selectionBar', 'selection-inset': 'selectionIndent',
  'priority-edge': 'priorityEdge', 'line-width': 'lineWidth', 'reply-pane-min-height': 'replyPaneMinHeight',
};

function read(source, key) {
  if (source[key] === undefined) throw new Error(`Missing Harklight design token: ${key}`);
  return source[key];
}

function map(source, names, unit = '') {
  return Object.fromEntries(Object.entries(names).map(([name, key]) => [name, `${read(source, key)}${unit}`]));
}

function appearance(mode) {
  const { color, inboxRow, derived } = read(tokens, mode);
  return {
    ...map(color, colors),
    ...map(inboxRow, rowColors),
    ...map(derived.typeTint, tints),
    ...map(derived, { 'wash-urgent': 'urgentWash', 'wash-high': 'highWash', pane: 'replyPane', scrim: 'sheetDim' }),
  };
}

const roles = {
  'row-title': 'inboxMessageTitle', 'row-byline': 'rowByline', 'row-body': 'rowBody',
  'row-sender': 'rowSender', 'row-time': 'rowTime', 'priority-line': 'priorityLine',
  'digest-title': 'fyiDigestTitle', 'message-title': 'messageTitle', 'message-sender': 'messageSender',
  'message-body': 'messageBody', 'choice-title': 'choiceTitle', 'choice-detail': 'choiceDetail',
  suggested: 'suggested', 'sheet-title': 'sheetTitle', 'chat-turn': 'chatTurn',
  'chat-speaker': 'chatSpeaker', delivered: 'delivered', 'position-pill': 'positionPill',
};
const metrics = {
  face: ['family', (face) => read({ heading: 'var(--serif)', system: 'var(--sans)' }, face)],
  size: ['size', (value) => `${value}px`],
  weight: ['weight', String],
  lineHeight: ['line', String],
  tracking: ['tracking', (value) => `${value}em`],
};

const typography = Object.fromEntries(Object.entries(roles).flatMap(([prefix, role]) => {
  const style = read(tokens.type.styles, role);
  return Object.entries(metrics)
    .filter(([key]) => style[key] !== undefined)
    .map(([key, [suffix, format]]) => [`type-${prefix}-${suffix}`, format(style[key])]);
}));

function declarations(values, indent) {
  return Object.entries(values).map(([key, value]) => `${indent}--${key}: ${value};`).join('\n');
}

const shared = {
  'heading-family': JSON.stringify(read(tokens.type, 'headingFamily')),
  ...map(tokens.fyiDigest, digest),
  ...map(tokens.shape, shapes, 'px'),
  ...typography,
};
const css = `/* Generated by scripts/generate-design-tokens.mjs from
 * clickety-clacks/harklight-app Design/tokens.json at ${appCommit}.
 * Do not edit by hand. */
:root {
${declarations({ ...appearance('dark'), ...shared }, '  ')}
}

@media (prefers-color-scheme: light) {
  :root {
${declarations(appearance('light'), '    ')}
  }
}
`;

writeFileSync(new URL('../src/ui/design-tokens.generated.css', import.meta.url), css);
